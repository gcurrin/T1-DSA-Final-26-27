import org.junit.jupiter.api.Test;
import static org.junit.jupiter.api.Assertions.*;

class ValidSudokuTest {

    @Test
    void validSudoku() {
        String[][] sudokuBoard = {
                {".",".",".","4",".",".","7",".","9"},
                {".","5","6",".","8",".",".","2","."},
                {"7",".","9",".",".","3","4",".","."},
                {".","3",".","5",".","7",".","9","."},
                {"5",".","7",".","9",".","2",".","4"},
                {".","9",".","2",".","4",".","6","."},
                {".",".",".","6",".",".","9",".","2"},
                {".","7",".",".","1",".","3","4","."},
                {"9",".","2",".",".","5",".",".","8"}
        };
        assertTrue(ValidSudoku.ValidSudoku(sudokuBoard));
    }

    @Test
    void validSudoku_secondBoard() {
        String[][] board = {
                {"5","3",".",".","7",".",".",".","."},
                {"6",".",".","1","9","5",".",".","."},
                {".","9","8",".",".",".",".","6","."},
                {"8",".",".",".","6",".",".",".","3"},
                {"4",".",".","8",".","3",".",".","1"},
                {"7",".",".",".","2",".",".",".","6"},
                {".","6",".",".",".",".","2","8","."},
                {".",".",".","4","1","9",".",".","5"},
                {".",".",".",".","8",".",".","7","9"}
        };
        assertTrue(ValidSudoku.ValidSudoku(board));
    }

    @Test
    void invalidSudoku_duplicateInRow() {
        // Row 0 has two 7s (columns 4 and 6)
        String[][] board = {
                {"5","3",".",".","7",".","7",".","."},
                {"6",".",".","1","9","5",".",".","."},
                {".","9","8",".",".",".",".","6","."},
                {"8",".",".",".","6",".",".",".","3"},
                {"4",".",".","8",".","3",".",".","1"},
                {"7",".",".",".","2",".",".",".","6"},
                {".","6",".",".",".",".","2","8","."},
                {".",".",".","4","1","9",".",".","5"},
                {".",".",".",".","8",".",".","7","9"}
        };
        assertFalse(ValidSudoku.ValidSudoku(board));
    }

    @Test
    void invalidSudoku_duplicateInColumn() {
        String[][] board = {
                {"5","3",".",".","7",".",".",".","."},
                {"6",".",".","1","9","5",".",".","."},
                {".","9","8",".",".",".",".","6","."},
                {"8",".",".",".","6",".",".",".","3"},
                {"4",".",".","8",".","3",".",".","1"},
                {"7",".",".",".","2",".",".",".","6"},
                {".","6",".",".",".",".","2","8","."},
                {".",".",".","4","1","9",".",".","5"},
                {"5",".",".",".","8",".",".","7","9"}
        };
        assertFalse(ValidSudoku.ValidSudoku(board));
    }

    @Test
    void invalidSudoku_duplicateInBox() {
        String[][] board = {
                {"5","3","6",".","7",".",".",".","."},
                {"6",".",".","1","9","5",".",".","."},
                {".","9","8",".",".",".",".","6","."},
                {"8",".",".",".","6",".",".",".","3"},
                {"4",".",".","8",".","3",".",".","1"},
                {"7",".",".",".","2",".",".",".","6"},
                {".","6",".",".",".",".","2","8","."},
                {".",".",".","4","1","9",".",".","5"},
                {".",".",".",".","8",".",".","7","9"}
        };
        assertFalse(ValidSudoku.ValidSudoku(board));
    }
}